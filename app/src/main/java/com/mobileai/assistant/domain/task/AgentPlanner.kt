package com.mobileai.assistant.domain.task

import com.mobileai.assistant.domain.dot.DotProfile
import com.mobileai.assistant.domain.tool.ToolDefinition
import com.mobileai.assistant.domain.tool.ToolRegistry
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.contentOrNull
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import java.util.UUID

/**
 * Multi-step plan structure generated by LLMs or agent planners.
 */
@Serializable
data class GeneratedPlan(
    val title: String,
    val summary: String,
    val steps: List<GeneratedStep>
)

@Serializable
data class GeneratedStep(
    val title: String,
    val description: String,
    val toolName: String? = null,
    val argumentsJson: String? = null
)

/**
 * Intelligent agent planning engine implementing the workflow:
 * Observe -> Understand -> Plan -> Act -> Verify -> Recover.
 *
 * Formulates structured multi-step plans grounded strictly in available [ToolRegistry] capabilities.
 */
class AgentPlanner(
    private val toolRegistry: ToolRegistry
) {
    private val json = Json {
        ignoreUnknownKeys = true
        isLenient = true
    }

    /**
     * Builds a prompt for the model to generate a multi-step plan for [goal].
     */
    fun buildPlanningPrompt(
        goal: String,
        dot: DotProfile,
        availableTools: List<ToolDefinition> = toolRegistry.getAllTools()
    ): String {
        val toolsDescription = availableTools.joinToString("\n") { tool ->
            "- ${tool.name} (${tool.sensitivity}): ${tool.description} Schema: ${tool.parameterSchemaJson}"
        }

        return """
You are an autonomous AI Agent (${dot.name}).
Your objective is to decompose the user's high-level goal into a deterministic, multi-step execution plan.

USER GOAL:
"$goal"

AVAILABLE TOOLS:
$toolsDescription

INSTRUCTIONS:
1. Break down the goal into 1 to 5 sequential, verifiable steps.
2. For each step that requires tool execution, select an available tool and supply valid JSON arguments.
3. If no tool is needed for a step, leave toolName null.
4. Output ONLY a valid JSON object matching this schema:
{
  "title": "Short Task Title",
  "summary": "Summary of plan",
  "steps": [
    {
      "title": "Step 1 title",
      "description": "What this step accomplishes",
      "toolName": "tool_name_or_null",
      "arguments": { ... }
    }
  ]
}
        """.trimIndent()
    }

    /**
     * Parses and validates a raw model planning response into a list of [DotTaskStep]s.
     * Rejects nonexistent tools and repairs schema anomalies.
     */
    fun parsePlanResponse(rawResponse: String, taskId: String): List<DotTaskStep> {
        val jsonPayload = extractJsonPayload(rawResponse)
        if (jsonPayload.isBlank()) {
            return fallbackPlan(taskId, "Execute user goal: $rawResponse")
        }

        return try {
            val root = json.parseToJsonElement(jsonPayload).jsonObject
            val stepsArray = root["steps"]?.jsonArray ?: JsonArray(emptyList())

            val steps = mutableListOf<DotTaskStep>()
            for ((index, element) in stepsArray.withIndex()) {
                val stepObj = element.jsonObject
                val title = stepObj["title"]?.jsonPrimitive?.contentOrNull ?: "Step ${index + 1}"
                val description = stepObj["description"]?.jsonPrimitive?.contentOrNull ?: title
                val requestedTool = stepObj["toolName"]?.jsonPrimitive?.contentOrNull?.takeIf { it.isNotBlank() }

                // Validate tool exists in registry
                val validToolName = if (requestedTool != null && toolRegistry.getTool(requestedTool) != null) {
                    requestedTool
                } else {
                    null
                }

                val argsJson = stepObj["arguments"]?.toString() ?: "{}"

                steps.add(
                    DotTaskStep(
                        id = UUID.randomUUID().toString(),
                        taskId = taskId,
                        stepIndex = index,
                        title = title,
                        description = description,
                        toolName = validToolName,
                        toolInputJson = if (validToolName != null) argsJson else null
                    )
                )
            }

            if (steps.isNotEmpty()) steps else fallbackPlan(taskId, "Process goal")
        } catch (_: Exception) {
            fallbackPlan(taskId, "Process goal")
        }
    }

    /**
     * Creates a fallback plan when model parsing fails or when running offline.
     */
    fun fallbackPlan(taskId: String, goal: String): List<DotTaskStep> {
        return listOf(
            DotTaskStep(
                id = UUID.randomUUID().toString(),
                taskId = taskId,
                stepIndex = 0,
                title = "Analyze Objective",
                description = "Inspect goal and retrieve relevant context: $goal",
                toolName = "inspect_task",
                toolInputJson = """{"taskId":"$taskId"}"""
            ),
            DotTaskStep(
                id = UUID.randomUUID().toString(),
                taskId = taskId,
                stepIndex = 1,
                title = "Synthesize Results",
                description = "Format and finalize task output",
                toolName = "format_content",
                toolInputJson = """{"content":"Task execution for: $goal"}"""
            )
        )
    }

    private fun extractJsonPayload(text: String): String {
        val trimmed = text.trim()
        if (trimmed.startsWith("{") && trimmed.endsWith("}")) return trimmed

        // Extract from markdown code fences: ```json ... ```
        val fenceRegex = Regex("```(?:json)?\\s*([\\s\\S]*?)\\s*```", RegexOption.IGNORE_CASE)
        val match = fenceRegex.find(trimmed)
        if (match != null) {
            return match.groupValues[1].trim()
        }

        // Bracket matching fallback
        val start = trimmed.indexOf('{')
        val end = trimmed.lastIndexOf('}')
        if (start != -1 && end > start) {
            return trimmed.substring(start, end + 1)
        }

        return ""
    }
}

